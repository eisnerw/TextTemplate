    private static List<SyntaxNode> CallChain(SyntaxNode expression, out SyntaxNode receiver)
    {
        var calls = new List<SyntaxNode>();
        while (expression.Kind == SyntaxKind.Call) { calls.Add(expression); expression = expression.Children[0]; }
        calls.Reverse();
        receiver = expression;
        return calls;
    }

    private string? Annotation(SyntaxNode call, string context = "annotatedContext", bool lambda = true, ParsedSource? source = null)
    {
        var args = call.Children.Skip(1).SelectMany(child => child.Children).ToList();
        // TODO: Evaluate dynamic style arguments; literal styles are applied during composition.
        if (call.Value == "@MultilineStyle" && args.All(arg => arg.Kind == SyntaxKind.String))
            return (lambda ? context + " => " : "") + context + ".WithMultilineStyle(" + string.Join(", ", args.Select(arg => Quote(DecodeString(arg.Value!)))) + ")";
        if (call.Value == "@BulletStyle" && args.All(arg => arg.Kind == SyntaxKind.String))
            return (lambda ? context + " => " : "") + context + ".WithBulletStyle(" + string.Join(", ", args.Select(arg => Quote(DecodeString(arg.Value!)))) + ")";
        if (call.Value == "@BulletMode" && args.Count == 1 && args[0].Kind == SyntaxKind.String)
            return (lambda ? context + " => " : "") + context + ".WithBulletMode(" + Quote(DecodeString(args[0].Value!)) + ")";
        if (call.Value == "@DefaultIndent" && args.Count <= 1 && args.All(arg => arg.Kind is SyntaxKind.String or SyntaxKind.Number))
            return (lambda ? context + " => " : "") + context + ".WithDefaultIndent(" + (args.Count == 0 ? "null" : Quote(args[0].Kind == SyntaxKind.String ? DecodeString(args[0].Value!) : args[0].Value!)) + ")";
        if (call.Value == "@Falsy" && (args.Count == 0 || args.Count == 1 && args[0].Kind == SyntaxKind.Regex))
            return (lambda ? context + " => " : "") + context + ".WithFalsy(" + (args.Count == 0 ? "null" : "new TemplateRegex(" + Quote(args[0].Value!) + ", " + Quote(sourcePath + ":" + args[0].Span.Line + ":" + args[0].Span.Column) + ")") + ")";
        if (call.Value is "@DateTest" or "@DateFormat" && source is not null)
        {
            string DateArgument(SyntaxNode arg) => arg.Kind switch
            {
                SyntaxKind.String => Quote(DecodeString(arg.Value!)),
                SyntaxKind.Number => "EvaluationContext.ParseInteger(" + Quote(arg.Value!) + ")",
                SyntaxKind.Regex => "new TemplateRegex(" + Quote(arg.Value!) + ", " + Quote(sourcePath + ":" + arg.Span.Line + ":" + arg.Span.Column) + ")",
                SyntaxKind.Identifier => context + ".Lookup(" + Quote(arg.Value!) + ")",
                _ => context + ".Each(itemContext => new " + unitName + "(itemContext)." + Emit(arg, source) + "())"
            };
            return (lambda ? context + " => " : "") + context + (call.Value == "@DateTest" ? ".WithDateTest(" : ".WithDateFormat(") +
                Quote(sourcePath + ":" + call.Span.Line + ":" + call.Span.Column) +
                (args.Count == 0 ? "" : ", " + string.Join(", ", args.Select(DateArgument))) + ")";
        }
        if (call.Value == "@Include" && args.Count == 1 && source is not null)
        {
            string argument = args[0].Kind == SyntaxKind.String ? Quote(DecodeString(args[0].Value!))
                : args[0].Kind == SyntaxKind.Identifier ? context + ".Lookup(" + Quote(args[0].Value!) + ")"
                : context + ".Each(includeArgumentContext => new " + unitName + "(includeArgumentContext)." + Emit(args[0], source) + "())";
            return (lambda ? context + " => " : "") + context + ".Include(EvaluationContext.Compose(" + argument + "))";
        }
        if (args.Count != 1 || args[0].Kind != SyntaxKind.String) return null;
        string value = DecodeString(args[0].Value!);
        if (call.Value == "@MissingValue") return (lambda ? context + " => " : "") + context + ".WithMissingValue(" + Quote(value) + ")";
        return null;
    }

    private static SyntaxNode WithoutAnnotations(SyntaxNode expression)
    {
        if (expression.Kind != SyntaxKind.Call) return expression;
        var receiver = WithoutAnnotations(expression.Children[0]);
        return expression.Value!.StartsWith('@') ? receiver
            : expression with { Children = new[] { receiver }.Concat(expression.Children.Skip(1)).ToArray() };
    }

    private void EmitImport(ParsedSource source, SyntaxNode? original = null, string importName = "Import")
    {
        // visitNamedSubtemplate(..., bInclude=true) preprocesses the bracket contents
        // with a leading newline. The frozen lexer consumes that first newline on '[';
        // recognize its exposed leading Subtemplates: section here, not in the parser.
        original ??= source.Tree.Children[0];
        var calls = CallChain(original, out var receiver);
        if (receiver.Kind != SyntaxKind.InlineTemplate || calls.Any(call => !call.Value!.StartsWith('@') || Annotation(call, source: source) is null))
        {
            bodies.Append("    internal EvaluationContext " + importName + "()\n    {\n        throw new NotImplementedException(")
                .Append(Quote(source.Category + "/" + source.Name + ".template:" + original.Span.Line + ":" + original.Span.Column + ": This include unit requires unsupported execution features.")).Append(");\n    }\n\n");
            return;
        }
        var children = receiver.Children.ToList();
        if (children.FirstOrDefault() is { Kind: SyntaxKind.Text, Value: "Subtemplates:" })
        {
            var definitions = children.Skip(1).Where(child => child.Kind is not (SyntaxKind.NewLine or SyntaxKind.Whitespace)).ToList();
            if (definitions.Any(child => child.Kind != SyntaxKind.Context || child.Value != "explicit" || child.Children[0].Kind != SyntaxKind.NamedSubtemplate))
            {
                bodies.Append("    internal EvaluationContext " + importName + "()\n    {\n        throw new NotImplementedException(")
                    .Append(Quote(source.Category + "/" + source.Name + ".template:" + original.Span.Line + ":" + original.Span.Column + ": Unsupported include definition layout.")).Append(");\n    }\n\n");
                return;
            }
            children = [new(SyntaxKind.SubtemplateSection, receiver.Span, null, definitions)];
        }
        if (!children.SequenceEqual(receiver.Children)) receiver = receiver with { Children = children };
        IndexDefinitions(receiver);
        var definitionsToExport = children.Where(child => child.Kind == SyntaxKind.SubtemplateSection).SelectMany(child => child.Children)
            .Where(child => child.Kind == SyntaxKind.Context && child.Value == "explicit" && child.Children[0].Kind == SyntaxKind.NamedSubtemplate).ToList();
        string? registration = definitionsToExport.Count == 0 ? null : EmitDefinitions(receiver, definitionsToExport, source,
            definition => "definitionContext => new " + unitName + "(definitionContext)." + Emit(definition, source) + "()",
            "defineIncludedSubtemplates");
        // Definitions are exported, and annotations configure the caller before its receiver runs.
        var content = definitionsToExport.Count == 0 ? receiver : receiver with { Children = children.Where(child => child.Kind != SyntaxKind.SubtemplateSection).ToArray() };
        // Include output is discarded. Literal-only content needs no generated method;
        // expressions still execute, including any deferred feature failures.
        string? render = content.Children.All(IsLiteral) ? null : Emit(content, source);
        var import = new StringBuilder("    internal EvaluationContext " + importName + "()\n    {\n        EvaluationContext included = " + (registration is null ? "Context" : "DefineSubtemplates(" + registration + ")") + ";\n");
        foreach (var call in calls)
            import.Append("        included = ").Append(Annotation(call, "included", false, source)).Append(";\n");
        if (render is not null)
            import.Append("        _ = new ").Append(unitName).Append("(included).").Append(render).Append("();\n");
        import.Append("        return included;\n    }\n\n");
        bodies.Append(import);
    }

    private string EmitDefinitions(SyntaxNode owner, IEnumerable<SyntaxNode> definitions, ParsedSource source,
        Func<SyntaxNode, string> callback, string hint)
    {
        string name = Unique(hint, methodNames);
        var registrations = new List<string>();
        foreach (var definition in definitions.GroupBy(n => n.Children[0].Value!, StringComparer.Ordinal).Select(group => group.Last()))
        {
            string binding = callback(definition.Children[1]);
            string importer = Unique("include" + NamePart(definition.Children[0].Value!, upper: true), methodNames);
            EmitImport(source, definition.Children[1], importer);
            registrations.Add("        definitions.Add(" + Quote(definition.Children[0].Value!) + ", " + binding +
                ", includedContext => new " + unitName + "(includedContext)." + importer + "());");
        }
        foreach (SyntaxNode section in owner.Children.Where(child => child.Kind == SyntaxKind.SubtemplateSection))
            bodies.Append(SourceComment(section, source, "    "));
        bodies.Append("    private void ").Append(name).Append("(SubtemplateDefinitions definitions)\n    {\n")
            .Append(string.Join("\n", registrations)).Append("\n    }\n\n");
        return name;
    }

    private static bool HasComputedInclude(SyntaxNode node)
        => node.Kind == SyntaxKind.Call && node.Value == "@Include" && node.Children.Skip(1).SelectMany(child => child.Children).Any(arg => arg.Kind != SyntaxKind.String)
            || node.Children.Any(HasComputedInclude);

    private static IEnumerable<string> IncludeNames(SyntaxNode node)
    {
        if (node.Kind == SyntaxKind.Call && node.Value == "@Include")
            foreach (var arg in node.Children.Skip(1).SelectMany(child => child.Children))
                if (arg.Kind == SyntaxKind.String && arg.Value is { Length: > 3 } literal && literal[1] == '#')
                    yield return literal[2..^1];
        foreach (var child in node.Children)
            foreach (var name in IncludeNames(child)) yield return name;
    }

    private static string NamePart(string value, bool upper = false)
    {
        var result = new StringBuilder();
        bool capitalize = upper;
        foreach (char c in value)
        {
            if (!char.IsLetterOrDigit(c) && c != '_') { if (result.Length > 0) capitalize = true; continue; }
            result.Append(capitalize ? char.ToUpperInvariant(c) : c);
            capitalize = false;
        }
        if (result.Length == 0) result.Append(upper ? "Content" : "content");
        if (char.IsDigit(result[0])) result.Insert(0, upper ? "Item" : "item");
        string name = result.ToString();
        return Keywords.Contains(name) ? "@" + name : name;
    }

    private static string Unique(string name, HashSet<string> names)
    {
        string candidate = name;
        for (int suffix = 2; !names.Add(candidate); suffix++) candidate = name + "_" + suffix;
        return candidate;
    }

    private static string Hint(SyntaxNode node)
    {
        if (node.Kind == SyntaxKind.Interpolation) return Hint(node.Children[0]);
        if (node.Kind is SyntaxKind.Template or SyntaxKind.InlineTemplate or SyntaxKind.SharedTemplate)
        {
            var hole = node.Children.FirstOrDefault(child => child.Kind == SyntaxKind.Interpolation);
            if (hole is not null) return Hint(hole);
            string words = string.Concat(node.Children.Where(child => child.Kind == SyntaxKind.Text).Select(child => child.Value));
            return words.Length > 0 ? NamePart(words[..Math.Min(24, words.Length)]) : "content";
        }
        if (node.Kind == SyntaxKind.Identifier) return NamePart(node.Value!.Split('.').Last());
        if (node.Kind == SyntaxKind.NamedSubtemplate) return NamePart(node.Value!);
        if (node.Kind is SyntaxKind.Context or SyntaxKind.ContextWithFallback) return Hint(node.Children[0]);
        if (node.Kind == SyntaxKind.Call) return NamePart(node.Value!.TrimStart('@', '#'));
        if (node.Kind is SyntaxKind.Arrow or SyntaxKind.ThinArrow)
            return node.Children[0].Kind == SyntaxKind.Identifier ? Hint(node.Children[0]) + "Result" : "choice";
        return "content";
    }

    private void IndexDefinitions(SyntaxNode node)
    {
        if (node.Kind == SyntaxKind.SubtemplateSection)
            foreach (var definition in node.Children)
                if (definition.Kind == SyntaxKind.Context && definition.Children.Count > 1 &&
                    definition.Children[0].Kind == SyntaxKind.NamedSubtemplate)
                    definitionNames[definition.Children[1]] = definition.Children[0].Value!;
        foreach (var child in node.Children) IndexDefinitions(child);
    }

    private string MethodName(SyntaxNode node, ParsedSource source)
    {
        string name = ReferenceEquals(node, source.Tree) ? "Evaluate"
            : definitionNames.TryGetValue(node, out var definition) ? NamePart(definition)
            : "render" + NamePart(Hint(node), upper: true);
        return Unique(name, methodNames);
    }

    // Match the emitted operation's return type, not the eventual rendered text.
    // Inline calls go through Each: their result can be a fragment array, list, or missing value.
    private static string ExpressionType(SyntaxNode node, bool asCall = false)
    {
        if (asCall && node.Kind == SyntaxKind.InlineTemplate) return "object?";
        switch (node.Kind)
        {
            case SyntaxKind.Text: case SyntaxKind.Whitespace: case SyntaxKind.NewLine:
            case SyntaxKind.Continuation: case SyntaxKind.String:
                return "string";
            case SyntaxKind.Number:
                return "double";
            case SyntaxKind.Group: case SyntaxKind.Not: case SyntaxKind.Logical: case SyntaxKind.Relational:
                return "bool";
            case SyntaxKind.Template: case SyntaxKind.SharedTemplate: case SyntaxKind.InlineTemplate:
                return "TemplateContent";
            case SyntaxKind.Arguments:
                return "object?[]";
            case SyntaxKind.Interpolation:
                return ExpressionType(node.Children[0], asCall: true);
            case SyntaxKind.Context: case SyntaxKind.ContextWithFallback:
                return node.Value == "implicit" ? ExpressionType(node.Children[0], asCall: true) : "object?";
            case SyntaxKind.Arrow: case SyntaxKind.ThinArrow:
                string whenTrue = ExpressionType(node.Children[1], asCall: true);
                string? whenFalse = node.Children.Count > 2 ? ExpressionType(node.Children[2], asCall: true)
                    : node.Kind == SyntaxKind.ThinArrow ? "string" : null;
                if (whenFalse is null) return whenTrue.EndsWith('?') ? whenTrue : whenTrue + "?";
                if (whenTrue == whenFalse) return whenTrue;
                // A nullable branch and its nonnullable counterpart retain their underlying type.
                if (whenTrue == whenFalse + "?") return whenTrue;
                if (whenFalse == whenTrue + "?") return whenFalse;
                return "object?";
            default:
                // Lookups, dynamic calls and unfinished operations have no narrower proven type.
                return "object?";
        }
    }

    private string Emit(SyntaxNode node, ParsedSource source)
    {
        if (methods.TryGetValue(node, out var existing)) return existing;
        string name = MethodName(node, source);
        methods.Add(node, name);
        var previous = current;
        current = new MethodBody();
        string expression = Expression(node, source);
        string access = ReferenceEquals(node, source.Tree) ? "internal" : "private";
        string method = SourceComment(node, source, "    ") +
            "    " + access + " " + ExpressionType(node) + " " + name + "()\n    {\n" + Body(expression) + "    }\n\n";
        bodies.Insert(0, method);
        current = previous;
        return name;
    }

    private static string SourceComment(SyntaxNode node, ParsedSource source, string indent)
    {
        // Read the original span, not reconstructed tokens: retain the author's
        // quoting, indentation and template syntax. Prefix every C# line terminator
        // so even template text containing comment delimiters stays a comment.
        string text = source.Text.Substring(node.Span.Offset, node.Span.Length)
            .Replace("\r\n", "\n").Replace('\r', '\n')
            .Replace('\u0085', '\n').Replace('\u2028', '\n').Replace('\u2029', '\n');
        var comment = new StringBuilder(indent + "// Template:\n");
        foreach (string line in text.Split('\n'))
            comment.Append(indent).Append("//").Append(line.Length == 0 ? "" : " " + line).Append('\n');
        string path = source.Category + "/" + source.Name + ".template";
        comment.Append(indent).Append("// Source: ").Append(Quote(path))
            .Append(':').Append(node.Span.Line).Append(':').Append(node.Span.Column).Append('\n');
        return comment.ToString();
    }

    private string Body(string expression)
        => string.Concat(current.Functions) + string.Concat(current.Statements.Select(line => "        " + line + "\n")) +
            (current.Statements.Count > 0 ? "\n" : "") + "        return " + expression + ";\n";

    private static string DecodeString(string literal) => literal[0] == '"'
        ? JsonSerializer.Deserialize<string>(literal)!
        : literal[1..^1].Replace("\\n", "\n").Replace("\\'", "'").Replace("\\\\", "\\").Replace("\\/", "/");

    private static bool IsLiteral(SyntaxNode node) => node.Kind is SyntaxKind.Text or SyntaxKind.Whitespace or SyntaxKind.NewLine or SyntaxKind.Continuation ||
        node.Kind == SyntaxKind.Interpolation && node.Children[0].Kind == SyntaxKind.String;
    private static string Literal(SyntaxNode node) => node.Kind == SyntaxKind.Continuation ? " " :
        node.Kind == SyntaxKind.Interpolation ? DecodeString(node.Children[0].Value!) : node.Value!;
    private static bool IsLiteralBody(SyntaxNode node) => node.Kind == SyntaxKind.InlineTemplate && node.Children.All(IsLiteral);
    private static string LocalName(string name)
    {
        name = name.TrimStart('@');
        return NamePart(char.ToLowerInvariant(name[0]) + name[1..]);
    }

    private static string InterpolatedText(IReadOnlyList<SyntaxNode> children, Func<SyntaxNode, string> expression)
    {
        string literals = string.Concat(children.Where(IsLiteral).Select(Literal));
        // Short templates stay on one line; multiline templates retain their visible layout.
        if (!literals.Contains('\n'))
        {
            var single = new StringBuilder("Line($\"");
            foreach (var child in children)
                if (IsLiteral(child)) single.Append(Quote(Literal(child))[1..^1].Replace("{", "{{").Replace("}", "}}"));
                else single.Append('{').Append(expression(child)).Append('}');
            return single.Append("\")").ToString();
        }
        static int LongestRun(string text, char character)
        {
            int longest = 0, current = 0;
            foreach (char c in text) { current = c == character ? current + 1 : 0; longest = Math.Max(longest, current); }
            return longest;
        }
        int dollars = Math.Max(2, Math.Max(LongestRun(literals, '{'), LongestRun(literals, '}')) + 1);
        string quotes = new('"', Math.Max(3, LongestRun(literals, '"') + 1));
        var content = new StringBuilder();
        foreach (var child in children)
            if (IsLiteral(child)) content.Append(Literal(child));
            else content.Append('{', dollars).Append(expression(child)).Append('}', dollars);
        return "Line(" + new string('$', dollars) + quotes + "\n            " +
            content.ToString().Replace("\n", "\n            ") + "\n            " + quotes + ")";
    }

    private string Expression(SyntaxNode node, ParsedSource source, SyntaxNode? replayReceiver = null, bool contextProbe = false)
    {
        string Call(SyntaxNode child) => child.Kind == SyntaxKind.InlineTemplate
            ? "Each(" + RawChild(child) + ")" : child.Kind is SyntaxKind.Template or SyntaxKind.SharedTemplate
            ? "this." + Emit(child, source) + "()" : Expression(child, source, replayReceiver, contextProbe);
        string RawChild(SyntaxNode child, string context = "itemContext") => child.Kind switch
        {
            SyntaxKind.Identifier when !child.Value!.StartsWith('@') => context + " => " + context + ".Lookup(" + Quote(child.Value) + ")",
            SyntaxKind.NamedSubtemplate => context + " => " + context + ".Named(" + Quote(child.Value!) + ")",
            SyntaxKind.String => context + " => " + Quote(DecodeString(child.Value!)),
            SyntaxKind.Number => context + " => EvaluationContext.ParseInteger(" + Quote(child.Value!) + ")",
            _ when IsLiteralBody(child) && !definitionNames.ContainsKey(child) => context + " => " + InterpolatedText(child.Children, _ => throw new InvalidOperationException()),
            _ => context + " => new " + unitName + "(" + context + ")." + Emit(child, source) + "()"
        };
        string InChild(SyntaxNode child, string context = "dataContext") => child.Kind is SyntaxKind.InlineTemplate or SyntaxKind.NamedSubtemplate
            ? context + " => " + context + ".Each(" + RawChild(child) + ")" : RawChild(child, context);
        string Predicate(SyntaxNode child) => child.Kind switch
        {
            SyntaxKind.Relational or SyntaxKind.Logical or SyntaxKind.Not or SyntaxKind.Group => Call(child),
            SyntaxKind.Identifier when !child.Value!.StartsWith('@') => "IsTruthy(" + Quote(child.Value) + ")",
            _ => "Context.TestCondition(" + Call(child) + ")"
        };
        string location = source.Category + "/" + source.Name + ".template:" + node.Span.Line + ":" + node.Span.Column;
        string Stub()
        {
            string operation = node.Kind switch
            {
                SyntaxKind.InlineCall => "applyInline",
                SyntaxKind.Regex => "pattern",
                SyntaxKind.Bullet => "bullet",
                SyntaxKind.Call => "apply" + NamePart(node.Value!.TrimStart('@', '#'), upper: true),
                _ => "read" + NamePart(node.Value ?? node.Kind.ToString(), upper: true)
            };
            string function = Unique(operation, current.Names);
            // Local functions retain lazy operand evaluation, including nested unsupported calls.
            var operands = node.Children.Select(child => "() => " + Call(child)).ToList();
            current.Functions.Add(SourceComment(node, source, "        ") + "        object? " + function + "() => Unsupported(\n" +
                "            " + Quote(node.Kind + (node.Value is null ? "" : " " + node.Value)) + ",\n" +
                "            " + Quote(location) + (operands.Count == 0 ? "" : ",\n            " + string.Join(",\n            ", operands)) + ");\n\n");
            return function + "()";
        }
        string expression;
        switch (node.Kind)
        {
            case SyntaxKind.Template:
            case SyntaxKind.SharedTemplate:
            case SyntaxKind.InlineTemplate:
                var children = node.Children.Where(n => n.Kind != SyntaxKind.SubtemplateSection).ToList();
                // Legacy bullet rules own the preceding newline and following spaces.
                // Keep them on the bullet so repeated list items inherit the entire marker.
                for (int i = 0; i < children.Count; i++)
                {
                    if (children[i].Kind != SyntaxKind.Bullet) continue;
                    var bulletNode = children[i];
                    string marker = bulletNode.Value!;
                    if (i > 0 && children[i - 1].Kind == SyntaxKind.NewLine)
                    {
                        marker = children[i - 1].Value + marker;
                        children.RemoveAt(i - 1); i--;
                    }
                    if (i + 1 < children.Count && children[i + 1].Kind == SyntaxKind.Whitespace)
                    {
                        marker += children[i + 1].Value;
                        children.RemoveAt(i + 1);
                    }
                    children[i] = bulletNode with { Value = marker };
                }
                expression = InterpolatedText(children, child =>
                {
                    string value = Call(child);
                    string local = Unique(LocalName(Hint(child)), current.Names);
                    current.Statements.Add(ExpressionType(child, asCall: true) + " " + local + " = " + value + ";");
                    return local;
                });
                var definitions = node.Children.Where(n => n.Kind == SyntaxKind.SubtemplateSection)
                    .SelectMany(n => n.Children).Where(n => n.Kind == SyntaxKind.Context && n.Value == "explicit" && n.Children[0].Kind == SyntaxKind.NamedSubtemplate).ToList();
                if (definitions.Count > 0)
                {
                    string registration = EmitDefinitions(node, definitions, source,
                        definition => InChild(definition, "definitionContext"),
                        ReferenceEquals(node, source.Tree) ? "defineSubtemplates" : methods[node] + "Definitions");
                    string contentName = Unique(ReferenceEquals(node, source.Tree) ? "render" + unitName : methods[node] + "Content", methodNames);
                    bodies.Append(SourceComment(node, source, "    ")).Append("    private TemplateContent ").Append(contentName)
                        .Append("()\n    {\n").Append(Body(expression)).Append("    }\n\n");
                    current = new MethodBody();
                    expression = "WithDefinitions(" + registration + ",\n            definitionContext => new " + unitName + "(definitionContext)." + contentName + "())";
                }
                break;
            case SyntaxKind.Text: case SyntaxKind.Whitespace: case SyntaxKind.NewLine:
                expression = Quote(node.Value!); break;
            case SyntaxKind.Continuation: expression = "\" \""; break;
            case SyntaxKind.Interpolation: expression = Call(node.Children[0]); break;
            case SyntaxKind.Identifier:
                expression = node.Value!.StartsWith('@') ? Stub() : "Get(" + Quote(node.Value!) + ")"; break;
            case SyntaxKind.NamedSubtemplate: expression = "Each(itemContext => itemContext.Named(" + Quote(node.Value!) + "))"; break;
            case SyntaxKind.String:
                expression = Quote(DecodeString(node.Value!)); break;
            case SyntaxKind.Number: expression = "EvaluationContext.ParseInteger(" + Quote(node.Value!) + ")"; break;
            case SyntaxKind.Group: expression = Predicate(node.Children[0]); break;
            case SyntaxKind.Not: expression = "!(" + Predicate(node.Children[0]) + ")"; break;
            case SyntaxKind.Logical:
                expression = "(" + Predicate(node.Children[0]) + (node.Value == "&" ? " && " : " || ") + Predicate(node.Children[1]) + ")"; break;
            case SyntaxKind.Relational:
                expression = "EvaluationContext.Compare(" + Call(node.Children[0]) + ", " + Quote(node.Value!) + ", " + Call(node.Children[1]) + ")"; break;
            case SyntaxKind.Arrow: case SyntaxKind.ThinArrow:
                expression = "(" + Predicate(node.Children[0]) + " ? " + Call(node.Children[1]) + " : " +
                    (node.Children.Count > 2 ? Call(node.Children[2]) : node.Kind == SyntaxKind.ThinArrow ? "\"\"" : "null") + ")"; break;
            case SyntaxKind.Context: case SyntaxKind.ContextWithFallback:
                if (node.Value == "implicit") expression = Call(node.Children[0]);
                else if (node.Children[0].Kind == SyntaxKind.Call && CallChain(node.Children[0], out _).Any(call => call.Value is "GroupBy" or "OrderBy"))
                {
                    var contextCall = node.Children[0];
                    CallChain(contextCall, out var originalReceiver);
                    string replayName = Unique(contextCall.Value == "OrderBy" ? "orderLoadedData" : "groupLoadedData", methodNames);
                    var previousBody = current;
                    current = new MethodBody();
                    string replayExpression = Expression(contextCall, source, originalReceiver);
                    bodies.Append(SourceComment(contextCall, source, "    ")).Append("    private object? ").Append(replayName)
                        .Append("()\n    {\n").Append(Body(replayExpression)).Append("    }\n\n");
                    current = previousBody;
                    expression = "InContext(" + Expression(contextCall, source, contextProbe: true) + ", " + InChild(node.Children[1]) +
                        (node.Kind == SyntaxKind.ContextWithFallback ? ", () => " + Call(node.Children[2]) : ", null") +
                        ", dataContext => new " + unitName + "(dataContext)." + replayName + "())";
                }
                else expression = "InContext(" + Call(node.Children[0]) + ", " + InChild(node.Children[1]) +
                    (node.Kind == SyntaxKind.ContextWithFallback ? ", () => " + Call(node.Children[2]) : "") + ")";
                break;
            case SyntaxKind.Arguments:
                expression = "new object?[] { " + string.Join(", ", node.Children.Select(Call)) + " }"; break;
            case SyntaxKind.Call:
                var calls = CallChain(node, out var receiver);
                var annotations = calls.Where(call => call.Value!.StartsWith('@')).ToList();
                if (annotations.Count > 0)
                {
                    if (receiver.Kind is not (SyntaxKind.InlineTemplate or SyntaxKind.NamedSubtemplate) || annotations.Any(call => Annotation(call, source: source) is null))
                        expression = Stub();
                    else
                    {
                        var body = WithoutAnnotations(node);
                        expression = "Annotate(\n            new Func<EvaluationContext, EvaluationContext>[]\n            {\n                " +
                            string.Join(",\n                ", annotations.Select(call => Annotation(call, source: source))) + "\n            },\n            " + InChild(body, "annotatedContext") + ")";
                    }
                }
                else if (node.Value is "GroupBy" or "OrderBy")
                {
                    var groupArgs = node.Children.Skip(1).SelectMany(child => child.Children).ToList();
                    string keyText = groupArgs.Count == 0 ? "" : source.Text.Substring(groupArgs[0].Span.Offset, groupArgs[0].Span.Length);
                    string selector = groupArgs.Count == 0 ? "itemContext => null" : RawChild(groupArgs[0]);
                    string input = ReferenceEquals(node.Children[0], replayReceiver) ? "Context.Current" : node.Children[0].Kind == SyntaxKind.Call || receiver.Value?.StartsWith('^') == true ? Call(node.Children[0])
                        : "MethodInput(" + RawChild(node.Children[0]) + ")";
                    expression = "Context." + node.Value + "(" + input + ", " + selector + ", " + Quote(keyText) + ", " +
                        "new object?[] { " + string.Join(", ", groupArgs.Skip(1).Select(Call)) + " }, " + (contextProbe ? "true" : "false") + ")";
                }
                else if (node.Value == "Case")
                {
                    var caseArgs = node.Children.Skip(1).SelectMany(child => child.Children).ToList();
                    // TODO: Characterize too-short Case argument forms (fewer than three arguments).
                    if (caseArgs.Count < 3) expression = Stub();
                    else
                    {
                        string function = Unique("selectCase", current.Names);
                        string input = ReferenceEquals(node.Children[0], replayReceiver) ? "Context.Current" : node.Children[0].Kind == SyntaxKind.Call ? Call(node.Children[0])
                            : "MethodInput(" + RawChild(node.Children[0]) + ")";
                        var body = new StringBuilder(SourceComment(node, source, "        "));
                        body.Append("        object? ").Append(function).Append("(object? value)\n        {\n")
                            .Append("            value = EvaluationContext.Intermediate(value);\n")
                            .Append("            if (value is null or EvaluationContext.Missing) return value;\n")
                            .Append("            if (value is EvaluationContext.Data or EvaluationContext.Arguments) return null;\n")
                            .Append("            switch (value)\n            {\n");
                        for (int i = 0; i < caseArgs.Count - 1; i += 2)
                            body.Append("                case var candidate when Builtins.CaseMatches(candidate, ").Append(Call(caseArgs[i])).Append("):\n")
                                .Append("                    return EvaluationContext.Intermediate(").Append(Call(caseArgs[i + 1])).Append(");\n");
                        body.Append("                default:\n                    return ").Append(caseArgs.Count % 2 == 0 ? "value" : "EvaluationContext.Intermediate(" + Call(caseArgs[^1]) + ")").Append(";\n")
                            .Append("            }\n        }\n\n");
                        current.Functions.Add(body.ToString());
                        expression = "EvaluationContext.Invoke(" + input + ", " + function + ")";
                    }
                }
                // TODO: Implement Count(predicate) with per-item predicate evaluation.
                else if (node.Value!.StartsWith('#') || (node.Value == "Count" && !node.Children.Skip(1).SelectMany(child => child.Children).Any()) || node.Value is "ToDate" or "Compose" or "Where" or "IfMissing" or "Join" or "Align" or "Trim" or "StartsWith" or "EndsWith" or "Contains" or "Replace" or "Substr" or "IndexOf" or "LastIndexOf" or "EndIndexOf" or "ToUpper" or "ToLower" or "GreaterThan" or "LessThan" or "Matches" or "Assert")
                {
                    // TODO: Where must evaluate its predicate in each item's context; skip it for this temporary pass-through.
                    string arguments = node.Value == "Where" ? "" : string.Join(", ", node.Children.Skip(1).SelectMany(child => child.Children).Select(Call));
                    string input = ReferenceEquals(node.Children[0], replayReceiver) ? "Context.Current" : node.Children[0].Kind == SyntaxKind.Call || receiver.Value?.StartsWith('^') == true ? Call(node.Children[0]) : node.Children[0].Kind == SyntaxKind.Identifier && !node.Children[0].Value!.StartsWith('@')
                        ? "MethodInput(" + Quote(node.Children[0].Value!) + ")"
                        : node.Children[0].Kind == SyntaxKind.NamedSubtemplate
                        ? "SubtemplateInput(" + Quote(node.Children[0].Value!) + ")"
                        : "MethodInput(" + RawChild(node.Children[0]) + ")";
                    string methodValue = Unique("methodValue", current.Names);
                    expression = "EvaluationContext.Invoke(" + input + ", " + methodValue + " => " +
                        (!node.Value.StartsWith('#') ? (node.Value == "ToDate" ? "Context.ToDate(" + Quote(location) + ", " : "Builtins." + node.Value + "(" + (node.Value == "Compose" ? "Context, " : "")) : "ApplySubtemplate(" + Quote(node.Value[1..]) + ", ") +
                        methodValue + (arguments.Length == 0 ? "" : ", " + arguments) + "))";
                }
                else expression = Stub();
                break;
            case SyntaxKind.Regex:
                expression = "new TemplateRegex(" + Quote(node.Value!) + ", " + Quote(location) + ")";
                break;
            case SyntaxKind.Bullet:
                string bullet = node.Value!;
                if (!bullet.Contains('\n'))
                {
                    int start = node.Span.Offset;
                    int bracket = source.Text.LastIndexOf('[', Math.Max(0, start - 1));
                    if (bracket >= 0)
                    {
                        string before = source.Text[(bracket + 1)..start];
                        if (before.Contains('\n') && !before.Contains('`') && before.All(char.IsWhiteSpace))
                            bullet = before[before.IndexOf('\n')..] + bullet;
                    }
                }
                expression = "Context.CreateBullet(" + Quote(bullet.Replace("{", "\u0001{")) + ")"; break;
            case SyntaxKind.InlineCall:
                expression = Stub(); break;
            default: expression = Stub(); break;
        }
        return expression;
    }
