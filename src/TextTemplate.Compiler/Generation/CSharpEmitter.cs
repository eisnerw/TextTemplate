    public GenerationResult Generate(CompilationDocument document, string? selectedTemplate = null)
    {
        methods.Clear(); methodNames.Clear(); definitionNames.Clear(); bodies.Clear();
        var diagnostics = new List<Diagnostic>();
        var shared = document.Sources.Where(p => p.Value.Category == "subtemplates")
            .ToDictionary(p => p.Value.Name, p => p, StringComparer.Ordinal);
        var selected = new SortedDictionary<string, ParsedSource>(StringComparer.Ordinal);
        foreach (var pair in document.Sources.Where(p => p.Value.Category == "templates" && (selectedTemplate is null || p.Value.Name == selectedTemplate)))
            selected.Add(pair.Key, pair.Value);
        if (selectedTemplate is not null && selected.Count == 0) throw new ArgumentException("Template not found: " + selectedTemplate);
        if (selectedTemplate is null || selected.Values.Any(source => HasComputedInclude(source.Tree)))
            foreach (var dependency in shared.Values) selected.TryAdd(dependency.Key, dependency.Value);
        var queue = new Queue<KeyValuePair<string, ParsedSource>>(selected);
        while (queue.TryDequeue(out var item))
        {
            if (HasComputedInclude(item.Value.Tree))
                foreach (var dependency in shared.Values)
                    if (selected.TryAdd(dependency.Key, dependency.Value)) queue.Enqueue(dependency);
            var locals = item.Value.Definitions.Select(d => d.Name).ToHashSet(StringComparer.Ordinal);
            foreach (var reference in item.Value.References)
            {
                if (locals.Contains(reference.Name)) continue;
                if (shared.TryGetValue(reference.Name, out var dependency))
                {
                    if (selected.TryAdd(dependency.Key, dependency.Value)) queue.Enqueue(dependency);
                }
                // Binding can depend on caller scope and @Include; defer missing-name checks to execution.
            }
        }
        foreach (var (key, source) in selected)
        {
            var text = new SourceText(key, source.Text);
            Validate(source.Tree, text, diagnostics);
        }
        if (diagnostics.Count > 0) return new(null, diagnostics);

        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var mainMap = new List<string>(); var sharedMap = new List<string>(); var importMap = new List<string>();
        var unitNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "TemplateExtensions", "TemplateExtensionRegistration", "ExtensionCall", "ExtensionArguments", "ExtensionContext", "ValueLookup", "TemplateDebug", "TemplateValue", "GeneratedTemplates", "EvaluationContext", "TemplateContent", "TemplateUnit", "Builtins", "NodeCasing", "TemplateRegex", "TemplateDate", "BulletIndent", "SubtemplateDefinitions", "GeneratedTemplateProgram", "Common",
            "System", "StringComparer", "StringComparison", "JsonElement", "JsonDocument", "JsonValueKind",
            "Dictionary", "List", "Func", "Action", "Regex", "CultureInfo", "Math", "Console", "File",
            "Exception", "ArgumentException", "InvalidOperationException", "NotImplementedException"
        };
        var units = selected.ToDictionary(pair => pair.Key, pair => Unique(NamePart(pair.Value.Name, upper: true), unitNames), StringComparer.Ordinal);
        var includes = selected.Values.SelectMany(source => IncludeNames(source.Tree)).ToHashSet(StringComparer.Ordinal);
        foreach (var (key, source) in selected)
        {
            bodies.Clear(); plumbing.Clear();
            methodNames.Clear();
            unitName = units[key];
            methodNames.UnionWith(new[] { unitName, "Get", "Line", "Named", "InContext", "WithDefinitions", "Unsupported", "Annotate", "Builtins", "Import", "Context", "Each", "MethodInput", "IsTruthy", "SubtemplateInput", "ApplySubtemplate", "SubtemplateDefinitions", "DefineSubtemplates", "Value", "Field", "Subtemplate", "EvaluateSubtemplate", "ForItem", "InScope", "TemplateValue", "Read", "Collect", "WithScope", "RegisterEach", "SourceLocation", "External" });
            IndexDefinitions(source.Tree);
            if (source.Category == "subtemplates")
            {
                EmitImport(source);
                importMap.Add($"        [{Quote(source.Name)}] = context => new {unitName}(context).Import(),");
            }
            string method = Emit(source.Tree, source);
            var entry = $"        [{Quote(source.Name)}] = context => new {unitName}(context).{method}(),";
            (source.Category == "templates" ? mainMap : sharedMap).Add(entry);
            string path = source.Category == "templates" ? "Templates/" + unitName + ".cs"
                : includes.Contains(source.Name) ? "Includes/" + unitName + ".cs" : "Includes/Common.cs";
            string unit = $"internal sealed partial class {unitName}(EvaluationContext context) : TemplateUnit<{unitName}>(context, child => new {unitName}(child))\n{{\n" + string.Concat(bodies.OrderBy(body => body.Priority).ThenBy(body => body.Offset).Select(body => body.Text)) + "}\n";
            string registrationUnit = $"internal sealed partial class {unitName}\n{{\n" + plumbing + "}\n";
            if (plumbing.Length > 0)
            {
                string registrationPath = "Registration/" + unitName + ".cs";
                files[registrationPath] = Header + registrationUnit;
            }
            files[path] = files.TryGetValue(path, out var previous) ? previous + "\n" + unit : Header + unit;
        }
        string runtimeName = typeof(CSharpEmitter).Assembly.GetManifestResourceNames().Single(n => n.EndsWith("StandaloneRuntime.cs.txt", StringComparison.Ordinal));
        using var reader = new StreamReader(typeof(CSharpEmitter).Assembly.GetManifestResourceStream(runtimeName)!);
        string runtime = reader.ReadToEnd();
        files.Add("GeneratedTemplates.cs", Header +
            "public static class GeneratedTemplates\n{\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, object?>> Templates = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", mainMap) + "\n    };\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, object?>> Shared = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", sharedMap) + "\n    };\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, EvaluationContext>> Imports = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", importMap) + "\n    };\n" +
            "    public static string Render(string name, JsonElement? data = null, string? dataRoot = null, TemplateExtensions? extensions = null, Action<string>? reportError = null)\n    {\n" +
            "        if (!Templates.TryGetValue(name, out Func<EvaluationContext, object?>? template)) throw new ArgumentException(\"Unknown template: \" + name);\n" +
            "        return (string)EvaluationContext.At(nameof(GeneratedTemplates), () => new EvaluationContext(data, Shared, dataRoot, Imports, extensions, reportError).Render(template) ?? \"\")!;\n    }\n\n" + "}\n");
        int programStart = runtime.IndexOf("public static class GeneratedTemplateProgram", StringComparison.Ordinal);
        files.Add("Support/EvaluationContext.cs", Header + runtime[..programStart]);
        files.Add("Program.cs", Header + runtime[programStart..]);
        files.Add("Support/TemplateUnit.cs", Header + UnitSupport);
        files.Add("Support/TemplateExtensions.cs", Header + ReadSupport("StandaloneExtensions.cs.txt"));
        files.Add("Support/TemplateValue.cs", Header + ReadSupport("StandaloneValue.cs.txt"));
        files.Add("Support/TemplateDebug.cs", Header + ReadSupport("StandaloneDebug.cs.txt"));
        files.Add("Support/Builtins.cs", Header + ReadSupport("StandaloneBuiltins.cs.txt"));
        files.Add("Support/TemplateDate.cs", Header + ReadSupport("StandaloneDate.cs.txt"));
        files.Add("Support/TemplateContent.cs", Header + ContentSupport);
        files.Add("Support/BulletIndent.cs", Header + ReadSupport("StandaloneBullets.cs.txt"));
        files.Add("Support/TemplateRegex.cs", Header + ReadSupport("StandaloneRegex.cs.txt"));
        files.Add("Support/NodeCasing.cs", Header + ReadSupport("StandaloneCasing.cs.txt") + ReadSupport("StandaloneCasingData.cs.txt"));
        string result = Header + string.Join("\n", files.Values.Select(file => file[Header.Length..]));
        return new(result, diagnostics) { Files = files };
    }

    private static void Validate(SyntaxNode node, SourceText source, List<Diagnostic> diagnostics)
    {
        if (node.Kind == SyntaxKind.String && node.Value![0] == '"')
        {
            try { JsonSerializer.Deserialize<string>(node.Value); }
            catch (JsonException) { diagnostics.Add(source.Error("Invalid JSON string literal.", node.Span).Diagnostic); }
        }
        foreach (var child in node.Children) Validate(child, source, diagnostics);
    }
