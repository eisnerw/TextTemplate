using System.Text;
using System.Text.Json;
using TextTemplate.Compiler.Parsing;

namespace TextTemplate.Compiler.Generation;

public sealed record GenerationResult(string? Source, IReadOnlyList<Diagnostic> Diagnostics)
{
    public IReadOnlyDictionary<string, string> Files { get; init; } = new SortedDictionary<string, string>(StringComparer.Ordinal);
    public bool Success => Source is not null && Diagnostics.Count == 0;
}

public sealed class CSharpEmitter
{
    private readonly Dictionary<SyntaxNode, string> methods = new(ReferenceEqualityComparer.Instance);
    private readonly HashSet<string> methodNames = new(StringComparer.Ordinal);
    private readonly Dictionary<SyntaxNode, string> definitionNames = new(ReferenceEqualityComparer.Instance);
    private readonly StringBuilder bodies = new();
    private string unitName = "";
    private string sourcePath = "";
    private sealed class MethodBody
    {
        internal readonly HashSet<string> Names = new(StringComparer.Ordinal) { "Builtins", "context", "itemContext", "dataContext", "definitionContext", "annotatedContext", "includedContext", "Get", "Line", "Named", "Unsupported", "InContext", "WithDefinitions", "MethodInput", "IsTruthy", "SubtemplateInput", "ApplySubtemplate", "SubtemplateDefinitions", "DefineSubtemplates" };
        internal readonly List<string> Statements = new();
        internal readonly List<string> Functions = new();
    }
    private MethodBody current = new();
    private static readonly HashSet<string> Keywords = new("abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while record required file scoped var dynamic await async yield partial global".Split(' '), StringComparer.Ordinal);
    private const string Header = "// Generated by TextTemplate.Compiler. Editable standalone C#; regeneration replaces edits.\n#nullable enable\nusing System;\nusing System.Collections.Generic;\nusing System.Globalization;\nusing System.IO;\nusing System.Text.Json;\nusing System.Text.RegularExpressions;\n\n";
    private static readonly JsonSerializerOptions LiteralOptions = new() { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
    private static string Quote(string text) => JsonSerializer.Serialize(text, LiteralOptions);

    public GenerationResult Generate(CompilationDocument document, string? selectedTemplate = null)
    {
        methods.Clear(); methodNames.Clear(); definitionNames.Clear(); bodies.Clear();
        var diagnostics = new List<Diagnostic>();
        var shared = document.Sources.Where(p => p.Value.Category == "subtemplates")
            .ToDictionary(p => p.Value.Name, p => p, StringComparer.Ordinal);
        var selected = new SortedDictionary<string, ParsedSource>(StringComparer.Ordinal);
        foreach (var pair in document.Sources.Where(p => p.Value.Category == "templates" && (selectedTemplate is null || p.Value.Name == selectedTemplate)))
            selected.Add(pair.Key, pair.Value);
        if (selectedTemplate is not null && selected.Count == 0) throw new ArgumentException("Template not found: " + selectedTemplate);
        if (selectedTemplate is null || selected.Values.Any(source => HasComputedInclude(source.Tree)))
            foreach (var dependency in shared.Values) selected.TryAdd(dependency.Key, dependency.Value);
        var queue = new Queue<KeyValuePair<string, ParsedSource>>(selected);
        while (queue.TryDequeue(out var item))
        {
            if (HasComputedInclude(item.Value.Tree))
                foreach (var dependency in shared.Values)
                    if (selected.TryAdd(dependency.Key, dependency.Value)) queue.Enqueue(dependency);
            var locals = item.Value.Definitions.Select(d => d.Name).ToHashSet(StringComparer.Ordinal);
            foreach (var reference in item.Value.References)
            {
                if (locals.Contains(reference.Name)) continue;
                if (shared.TryGetValue(reference.Name, out var dependency))
                {
                    if (selected.TryAdd(dependency.Key, dependency.Value)) queue.Enqueue(dependency);
                }
                // Binding can depend on caller scope and @Include; defer missing-name checks to execution.
            }
        }
        foreach (var (key, source) in selected)
        {
            var text = new SourceText(key, source.Text);
            Validate(source.Tree, text, diagnostics);
        }
        if (diagnostics.Count > 0) return new(null, diagnostics);

        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var mainMap = new List<string>(); var sharedMap = new List<string>(); var importMap = new List<string>();
        var unitNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "GeneratedTemplates", "EvaluationContext", "TemplateContent", "TemplateUnit", "Builtins", "NodeCasing", "TemplateRegex", "TemplateDate", "BulletIndent", "SubtemplateDefinitions", "GeneratedTemplateProgram", "Common",
            "System", "StringComparer", "StringComparison", "JsonElement", "JsonDocument", "JsonValueKind",
            "Dictionary", "List", "Func", "Action", "Regex", "CultureInfo", "Math", "Console", "File",
            "Exception", "ArgumentException", "InvalidOperationException", "NotImplementedException"
        };
        var units = selected.ToDictionary(pair => pair.Key, pair => Unique(NamePart(pair.Value.Name, upper: true), unitNames), StringComparer.Ordinal);
        var includes = selected.Values.SelectMany(source => IncludeNames(source.Tree)).ToHashSet(StringComparer.Ordinal);
        foreach (var (key, source) in selected)
        {
            bodies.Clear();
            methodNames.Clear();
            unitName = units[key];
            sourcePath = source.Category + "/" + source.Name + ".template";
            methodNames.UnionWith(new[] { unitName, "Get", "Line", "Named", "InContext", "WithDefinitions", "Unsupported", "Annotate", "Builtins", "Import", "Context", "Each", "MethodInput", "IsTruthy", "SubtemplateInput", "ApplySubtemplate", "SubtemplateDefinitions", "DefineSubtemplates" });
            IndexDefinitions(source.Tree);
            if (source.Category == "subtemplates")
            {
                EmitImport(source);
                importMap.Add($"        [{Quote(source.Name)}] = context => new {unitName}(context).Import(),");
            }
            string method = Emit(source.Tree, source);
            var entry = $"        [{Quote(source.Name)}] = context => new {unitName}(context).{method}(),";
            (source.Category == "templates" ? mainMap : sharedMap).Add(entry);
            string path = source.Category == "templates" ? "Templates/" + unitName + ".cs"
                : includes.Contains(source.Name) ? "Includes/" + unitName + ".cs" : "Includes/Common.cs";
            string unit = $"internal sealed class {unitName}(EvaluationContext context) : TemplateUnit(context)\n{{\n" + bodies + "}\n";
            files[path] = files.TryGetValue(path, out var previous) ? previous + "\n" + unit : Header + unit;
        }
        string runtimeName = typeof(CSharpEmitter).Assembly.GetManifestResourceNames().Single(n => n.EndsWith("StandaloneRuntime.cs.txt", StringComparison.Ordinal));
        using var reader = new StreamReader(typeof(CSharpEmitter).Assembly.GetManifestResourceStream(runtimeName)!);
        string runtime = reader.ReadToEnd();
        files.Add("GeneratedTemplates.cs", Header +
            "public static class GeneratedTemplates\n{\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, object?>> Templates = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", mainMap) + "\n    };\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, object?>> Shared = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", sharedMap) + "\n    };\n" +
            "    private static readonly Dictionary<string, Func<EvaluationContext, EvaluationContext>> Imports = new(StringComparer.Ordinal)\n    {\n" + string.Join("\n", importMap) + "\n    };\n" +
            "    public static string Render(string name, JsonElement? data = null, string? dataRoot = null)\n    {\n" +
            "        if (!Templates.TryGetValue(name, out Func<EvaluationContext, object?>? template)) throw new ArgumentException(\"Unknown template: \" + name);\n" +
            "        return (string)EvaluationContext.At(\"templates/\" + name + \".template:1:1\", () => new EvaluationContext(data, Shared, dataRoot, Imports).Render(template) ?? \"\")!;\n    }\n\n" + "}\n");
        int programStart = runtime.IndexOf("public static class GeneratedTemplateProgram", StringComparison.Ordinal);
        files.Add("Support/EvaluationContext.cs", Header + runtime[..programStart]);
        files.Add("Program.cs", Header + runtime[programStart..]);
        files.Add("Support/TemplateUnit.cs", Header + UnitSupport);
        files.Add("Support/Builtins.cs", Header + ReadSupport("StandaloneBuiltins.cs.txt"));
        files.Add("Support/TemplateDate.cs", Header + ReadSupport("StandaloneDate.cs.txt"));
        files.Add("Support/TemplateContent.cs", Header + ContentSupport);
        files.Add("Support/BulletIndent.cs", Header + ReadSupport("StandaloneBullets.cs.txt"));
        files.Add("Support/TemplateRegex.cs", Header + ReadSupport("StandaloneRegex.cs.txt"));
        files.Add("Support/NodeCasing.cs", Header + ReadSupport("StandaloneCasing.cs.txt") + ReadSupport("StandaloneCasingData.cs.txt"));
        string result = Header + string.Join("\n", files.Values.Select(file => file[Header.Length..]));
        return new(result, diagnostics) { Files = files };
    }

    private static void Validate(SyntaxNode node, SourceText source, List<Diagnostic> diagnostics)
    {
        if (node.Kind == SyntaxKind.String && node.Value![0] == '"')
        {
            try { JsonSerializer.Deserialize<string>(node.Value); }
            catch (JsonException) { diagnostics.Add(source.Error("Invalid JSON string literal.", node.Span).Diagnostic); }
        }
        foreach (var child in node.Children) Validate(child, source, diagnostics);
    }
    private const string ContentSupport = """
        // Structured output, retained until the final rendering pass.
        // Argument arrays and input data are distinct from template content.
        public sealed class TemplateContent
        {
            internal object?[] Fragments { get; }
            internal TemplateContent(object?[] fragments) => Fragments = fragments;
            public string Render() => new EvaluationContext(null, new Dictionary<string, Func<EvaluationContext, object?>>()).Render(_ => this) ?? "";
            public override string ToString() => Render();
        }
        """;

    private static string ReadSupport(string name)
    {
        using var stream = typeof(CSharpEmitter).Assembly.GetManifestResourceStream("TextTemplate.Compiler.Generation." + name)!;
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    private const string UnitSupport = """
        // Short instance helpers keep compatibility machinery out of template bodies.
        internal abstract class TemplateUnit(EvaluationContext context)
        {
            protected EvaluationContext Context => context;
            protected object? Annotate(Func<EvaluationContext, EvaluationContext>[] annotations, Func<EvaluationContext, object?> body)
                => context.Annotate(annotations, body);
            protected object? ApplySubtemplate(string name, object? value, params object?[] arguments) => context.CallNamed(name, value, arguments);
            protected object? Each(Func<EvaluationContext, object?> body) => context.Each(body);
            // Collect method input in each current item context before invoking the method.
            protected object? MethodInput(Func<EvaluationContext, object?> body) => context.Receiver(body);
            protected object? MethodInput(string path) => MethodInput(itemContext => itemContext.Lookup(path));
            protected object? SubtemplateInput(string name) => MethodInput(itemContext => itemContext.Named(name));
            // Apply legacy truth rules to a lookup without converting its value to text.
            protected bool IsTruthy(string path) => context.TestCondition(Get(path));
            protected object? Get(string path) => context.Lookup(path);
            protected object? Named(string name) => context.Named(name);
            protected static TemplateContent Line(EvaluationContext.StructuredText text) => EvaluationContext.Text(text);
            protected object? InContext(object? value, Func<EvaluationContext, object?> body, Func<object?>? fallback = null, Func<EvaluationContext, object?>? replay = null)
                => context.Context(value, body, fallback, replay);
            // Registration creates bindings only; bodies run later in the caller's context.
            protected sealed class SubtemplateDefinitions
            {
                internal Dictionary<string, Func<EvaluationContext, object?>> Bindings { get; } = new(StringComparer.Ordinal);
                internal Dictionary<string, Func<EvaluationContext, EvaluationContext>> Imports { get; } = new(StringComparer.Ordinal);
                public void Add(string name, Func<EvaluationContext, object?> body, Func<EvaluationContext, EvaluationContext> import)
                { Bindings[name] = body; Imports[name] = import; }
