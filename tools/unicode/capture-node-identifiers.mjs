// Capture identifier properties from the pinned oracle, not .NET's Unicode version.
import { writeFileSync } from 'node:fs';
if (process.versions.node !== '24.22.0' || process.versions.unicode !== '17.0')
  throw new Error('Use reference Node 24.22.0 / Unicode 17.0 to regenerate these tables.');
function ranges(pattern) {
  const result = [];
  for (let code = 0; code <= 0x10ffff; code++) {
    if (!pattern.test(String.fromCodePoint(code))) continue;
    const last = result.at(-1);
    if (last && last[1] + 1 === code) last[1] = code;
    else result.push([code, code]);
  }
  return result.map(pair => '        ' + pair.map(code => '0x' + code.toString(16)).join(', ') + ',').join('\n');
}
const source = `// Generated by tools/unicode/capture-node-identifiers.mjs.
// Oracle: Node 24.22.0 / Unicode 17.0. Regenerate only with deliberate parity review.
internal static class NodeIdentifiers
{
    internal static bool IsStart(int code) => code is '$' or '_' || Contains(Start, code);
    internal static bool IsContinue(int code) => code is '$' or '_' or 0x200c or 0x200d || Contains(Continue, code);
    private static bool Contains(int[] ranges, int code)
    {
        int low = 0, high = ranges.Length / 2 - 1;
        while (low <= high)
        {
            int middle = (low + high) / 2;
            if (code < ranges[middle * 2]) high = middle - 1;
            else if (code > ranges[middle * 2 + 1]) low = middle + 1;
            else return true;
        }
        return false;
    }
    private static readonly int[] Start = {
${ranges(/\p{ID_Start}/u)}
    };
    private static readonly int[] Continue = {
${ranges(/\p{ID_Continue}/u)}
    };
}
`;
writeFileSync(new URL('../../src/TextTemplate.Compiler/Generation/StandaloneIdentifiers.cs.txt', import.meta.url), source);
